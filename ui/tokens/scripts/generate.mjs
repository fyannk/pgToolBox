// Writes tokens.ts from tokens.css and the vendored fyannk.css. `--check` verifies the committed file is
// current without writing it (the test and `make tokens` use it).

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { readTokens } from "./parse.mjs";

const root = new URL("..", import.meta.url);
const cssPath = fileURLToPath(new URL("tokens.css", root));
const fyPath = fileURLToPath(new URL("fyannk.css", root));
const tsPath = fileURLToPath(new URL("tokens.ts", root));

export function render() {
  const { light, dark } = readTokens(readFileSync(cssPath, "utf8"), readFileSync(fyPath, "utf8"));
  const names = Object.keys(light).sort();
  const q = (s) => JSON.stringify(s);
  const rec = (theme) => names.map((n) => `    ${q(n)}: ${q(theme[n] ?? light[n])},`).join("\n");
  return `// Generated by scripts/generate.mjs from tokens.css and fyannk.css; do not edit.
// SPDX-License-Identifier: Apache-2.0

export type Theme = "light" | "dark";

/** Every custom property tokens.css and fyannk.css declare, sorted. */
export const tokenNames = [
${names.map((n) => `  ${q(n)},`).join("\n")}
] as const;

export type TokenName = (typeof tokenNames)[number];

/** Resolved values by theme. A property a theme does not override carries the base value. */
export const tokens: Record<Theme, Record<TokenName, string>> = {
  light: {
${rec(light)}
  },
  dark: {
${rec(dark)}
  },
};

/** The CSS variable reference for a token: cssVar("--accent") is "var(--accent)". */
export function cssVar(name: TokenName): string {
  return \`var(\${name})\`;
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render();
  if (process.argv.includes("--check")) {
    if (readFileSync(tsPath, "utf8") !== out) {
      console.error("tokens.ts is stale; run `npm run generate` in ui/tokens");
      process.exit(1);
    }
  } else {
    writeFileSync(tsPath, out);
  }
}
