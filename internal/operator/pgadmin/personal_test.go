// personalRole is a per-person DatabaseRole as the console creates it:
// labelled, annotated with the pgAdmin user, its password generated by
// CloudNativePG (no passwordSecret).
func personalRole(name, user string) *cnpgv1.DatabaseRole {
	role := databaseRole(name, "cluster-1", "")
	role.Spec.PasswordSecret = nil
	role.Labels = map[string]string{pgtoolboxv1alpha1.LabelPersonalRole: pgtoolboxv1alpha1.PersonalRoleLabelValue}
	role.Annotations = map[string]string{pgtoolboxv1alpha1.AnnotationPgAdminUser: user}
	return role
}

func TestResolveOfferPersonalRoles(t *testing.T) {
	p := oauth2PgAdmin()
	p.Namespace = "team"
	alice := personalRole("alice", "alice@example.com")
	invalid := personalRole("mallory", "-x' or 1=1")
	privileged := personalRole("eve", "eve@example.com")
	privileged.Spec.InRoles = []string{"pg_read_all_data"}
	pending := personalRole("pending", "pending@example.com")
	pending.Status.SecretResourceVersion = "" // CloudNativePG has not generated it yet
	configRole := databaseRole("pgadmin_team", "cluster-1", "x")
	configRole.OwnerReferences = []metav1.OwnerReference{{APIVersion: pgtoolboxv1alpha1.GroupVersion.String(), Kind: "PgAdmin", Name: "team", UID: "u", Controller: new(true)}}

	result := resolveOffer(offerInputs{
		PgAdmin: p, Clusters: []cnpgv1.Cluster{*testCluster()},
		Roles: []cnpgv1.DatabaseRole{*alice, *invalid, *privileged, *pending, *configRole}, RolesAPI: apiIf(true),
	})
	var personal []string
	for _, s := range result.Document.Servers {
		if s.Owner != "" {
			personal = append(personal, s.Owner+"="+s.User+"/"+s.SecretName+"@"+s.SecretResourceVersion)
		}
		if s.User == "pgadmin_team" {
			t.Fatal("a PgAdmin's own settings database role is never offered")
		}
	}
	if !slices.Equal(personal, []string{"alice@example.com=alice/alice-password@7"}) {
		t.Fatalf("personal servers %v: the generated Secret, at the version CloudNativePG applied", personal)
	}
	if got := result.Document.Owners(); !slices.Equal(got, []string{"alice@example.com"}) {
		t.Fatalf("owners %v", got)
	}
	why := map[string]string{}
	for _, row := range result.Rows {
		if row.State == pgtoolboxv1alpha1.ServerStateNotOffered {
			why[row.User] = row.Message
		}
		if row.User == "alice" && row.PgAdminUser != "alice@example.com" {
			t.Fatalf("alice's row must name her pgAdmin user: %+v", row)
		}
	}
	for user, want := range map[string]string{
		"mallory": "personal role without a valid", "eve": "privileged", "pending": "none CloudNativePG generated",
	} {
		if !strings.Contains(why[user], want) {
			t.Errorf("%s: not offered because %q, want %q", user, why[user], want)
		}
	}
}

func TestRegistrationJobForgetsDroppedOwners(t *testing.T) {
	p := oauth2PgAdmin()
	p.Status.PersonalServerOwners = []string{"alice@example.com", "bob@example.com"}
	in := testInputs(p, false)
	in.Owners = []string{"alice@example.com"}
	command := buildRegistrationJob(p, in, strings.Repeat("a", 16)).Spec.Template.Spec.Containers[0].Command
	joined := strings.Join(command, " ")
	if !strings.Contains(joined, "--forget-owner bob@example.com") || strings.Contains(joined, "--forget-owner alice@example.com") {
		t.Fatalf("command %s", joined)
	}
}

func TestValidPgAdminUser(t *testing.T) {
	for user, want := range map[string]bool{
		"alice@example.com": true, "kube:admin": true, "system:serviceaccount:a:b": true,
		"": false, "-x": false, "a b": false, "a'b": false, `a\b`: false, "a\nb": false, strings.Repeat("a", 255): false,
	} {
		if got := ValidPgAdminUser(user); got != want {
			t.Errorf("%q: %v, want %v", user, got, want)
		}
	}
}
