// Package docsbundle is the documentation of the console's own version,
// embedded in the binary with a prebuilt BM25 index. An
// assistant answering about this console reads the pages this console was
// built with, not the site's newest: Search ranks sections (a "##" or "###"
// block) by keyword, Page returns a whole page.
//
// The bundle is one file, data/bundle.gz: a deterministic gzip archive of the
// Markdown pages and the index, decompressed once on first use and held in
// memory from then on. Its two budgets, MaxEmbeddedBytes (compressed: the
// binary and the image) and MaxBundleBytes (decompressed: the console's
// memory), are enforced by Build. It is generated by `make docs-bundle` from
// the documentation site's build, or by the console image's Dockerfile stages,
// and is not committed: only data/.keep is, so that `go build`, `go test` and
// lint work on a fresh clone. A binary built without the bundle has no
// documentation: Default reports ErrNotEmbedded and Search, Page, Pages and
// Version answer as for an empty bundle. The package depends on the standard
// library only.
package docsbundle

import (
	"embed"
	"errors"
	"fmt"
	"io/fs"
	"net/url"
	"sort"
	"strings"
	"sync"
	"unicode/utf8"
)

// all: so that data/.keep, the committed placeholder, matches on a fresh
// clone and the directive never fails to compile.
//
//go:embed all:data
var embedded embed.FS

// ErrNotEmbedded is what Load and Default report when the bundle is absent:
// the binary was built without `make docs-bundle` (a source build, a test
// binary). It is a state, not a failure: the console serves no docs tools.
var ErrNotEmbedded = errors.New("docsbundle: no documentation bundle embedded (build with make docs-bundle or the image Dockerfile)")

// Hit is one ranked section.
type Hit struct {
	// ChunkID is the section's identifier: the page path, then "#" and the
	// heading's anchor (the page path alone for the introduction).
	ChunkID string
	// PageTitle is the title of the page the section belongs to.
	PageTitle string
	// Section is the section's heading; the page title for an introduction.
	Section string
	// Version is the documentation version of the bundle.
	Version string
	// Path is the path the page is served at on the documentation site.
	Path string
	// Excerpt is a short extract of the section around the first matching word.
	Excerpt string
	// Score is the BM25 score; only its order is meaningful.
	Score float64
}

// Document is a documentation page.
type Document struct {
	// Path is the path the page is served at, e.g. /docs/console/tour/.
	Path string
	// Title is the page title.
	Title string
	// Version is the documentation version of the bundle.
	Version string
	// Markdown is the page body without front matter.
	Markdown string
}

// Bundle is a loaded documentation bundle.
type Bundle struct {
	files map[string]string // the archive's files, by name
	size  int               // the archive's decompressed size
	ix    *index
	pages map[string]int // normalised path -> index into ix.Pages
}

// Load reads a bundle laid out as `make docs-bundle` writes it: bundle.gz at
// the root of fsys. It is ErrNotEmbedded when there is none, and an error
// when the archive is corrupt, truncated or decompresses past a bound.
func Load(fsys fs.FS) (*Bundle, error) {
	archive, err := fs.ReadFile(fsys, archiveName)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, ErrNotEmbedded
	}
	if err != nil {
		return nil, fmt.Errorf("docsbundle: %w", err)
	}
	files, size, err := unpack(archive)
	if err != nil {
		return nil, err
	}
	ix, err := decodeIndex([]byte(files["index.bin"]))
	if err != nil {
		return nil, err
	}
	b := &Bundle{files: files, size: size, ix: ix, pages: map[string]int{}}
	for i, p := range ix.Pages {
		b.pages[normalizePath(p.Path)] = i
	}
	return b, nil
}

var (
	defaultOnce   sync.Once
	defaultBundle *Bundle
	defaultErr    error
)

// Default is the bundle embedded in the binary. It is loaded on first use;
// the error is ErrNotEmbedded when the binary was built without one.
func Default() (*Bundle, error) {
	defaultOnce.Do(func() {
		sub, err := fs.Sub(embedded, "data")
		if err != nil {
			defaultErr = err
			return
		}
		defaultBundle, defaultErr = Load(sub)
	})
	return defaultBundle, defaultErr
}

// Search ranks the embedded documentation's sections for a query. The query
// is plain words: identifiers such as history.persistent, kebab-case names
// and CamelCase condition types match as the whole and by their parts. limit
// is capped at 50 and defaults to 10 when it is not positive. No match, or an
// empty query, returns nil.
func Search(query string, limit int) []Hit {
	b, err := Default()
	if err != nil {
		return nil
	}
	return b.Search(query, limit)
}

// Page returns an embedded page by the path it is served at. The path may
// carry a trailing slash or none, a ".md" suffix, a fragment or query, or the
// site's origin; "/docs/console/tour", "docs/console/tour.md" and
// "/docs/console/tour/#clusters" are the same page.
func Page(path string) (Document, bool) {
	b, err := Default()
	if err != nil {
		return Document{}, false
	}
	return b.Page(path)
}

// Version is the documentation version of the embedded bundle: the release
// the console was built for.
func Version() string {
	b, err := Default()
	if err != nil {
		return ""
	}
	return b.Version()
}

// Pages lists the embedded pages in path order.
func Pages() []Document {
	b, err := Default()
	if err != nil {
		return nil
	}
	return b.Pages()
}

// Version is the bundle's documentation version.
func (b *Bundle) Version() string { return b.ix.Version }

// DecompressedSize is the size of the bundle's archive once decompressed:
// what it holds in memory besides the decoded index.
func (b *Bundle) DecompressedSize() int { return b.size }

// Search is the package-level Search on this bundle.
func (b *Bundle) Search(query string, limit int) []Hit {
	switch {
	case limit <= 0:
		limit = 10
	case limit > 50:
		limit = 50
	}
	hits := make([]Hit, 0, limit)
	for _, s := range b.ix.search(query, limit) {
		c := b.ix.Chunks[s.chunk]
		p := b.ix.Pages[c.Page]
		hits = append(hits, Hit{
			ChunkID:   c.ID,
			PageTitle: p.Title,
			Section:   c.Heading,
			Version:   b.ix.Version,
			Path:      p.Path,
			Excerpt:   b.excerpt(c, query),
			Score:     s.score,
		})
	}
	if len(hits) == 0 {
		return nil
	}
	return hits
}

// Page is the package-level Page on this bundle.
func (b *Bundle) Page(path string) (Document, bool) {
	i, ok := b.pages[normalizePath(path)]
	if !ok {
		return Document{}, false
	}
	return b.document(i)
}

// Pages is the package-level Pages on this bundle.
func (b *Bundle) Pages() []Document {
	out := make([]Document, 0, len(b.ix.Pages))
	for i := range b.ix.Pages {
		if d, ok := b.document(i); ok {
			out = append(out, d)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out
}

func (b *Bundle) file(p pageMeta) (string, bool) {
	data, ok := b.files["pages/"+p.File]
	return data, ok
}

func (b *Bundle) document(i int) (Document, bool) {
	p := b.ix.Pages[i]
	file, ok := b.file(p)
	if !ok {
		return Document{}, false
	}
	return Document{Path: p.Path, Title: p.Title, Version: b.ix.Version, Markdown: stripFrontMatter(file)}, true
}

// normalizePath reduces the spellings of a page path to one key: no origin,
// fragment, query, ".md" suffix, trailing "/index" or slashes.
func normalizePath(p string) string {
	p = strings.TrimSpace(p)
	if u, err := url.Parse(p); err == nil && u.Path != "" {
		p = u.Path
	} else if i := strings.IndexAny(p, "#?"); i >= 0 {
		p = p[:i]
	}
	p = strings.Trim(p, "/")
	p = strings.TrimSuffix(p, ".md")
	if p == "index" {
		return ""
	}
	return strings.Trim(strings.TrimSuffix(p, "/index"), "/")
}

const excerptRunes = 240

// excerpt is the start of a section's text, or a window around the first
// word of the query that occurs in it, with the heading and whitespace taken
// out.
func (b *Bundle) excerpt(c chunkMeta, query string) string {
	file, ok := b.file(b.ix.Pages[c.Page])
	if !ok || c.End > len(file) || c.Start > c.End {
		return ""
	}
	text := strings.TrimSpace(file[c.Start:c.End])
	if first, rest, found := strings.Cut(text, "\n"); found && strings.HasPrefix(first, "#") {
		text = rest
	}
	runes := []rune(strings.Join(strings.Fields(text), " "))
	if len(runes) == 0 {
		return ""
	}
	at := -1
	lower := []rune(strings.ToLower(string(runes)))
	if len(lower) == len(runes) {
		for _, w := range strings.FieldsFunc(strings.ToLower(query), func(r rune) bool { return !isWordRune(r) && !isJoiner(r) }) {
			if pos := indexRunes(lower, []rune(w)); pos >= 0 && (at < 0 || pos < at) {
				at = pos
			}
		}
	}
	start := max(at-60, 0) // at is -1 when no word of the query occurs
	// Begin on a word boundary when the window does not start the section.
	for start > 0 && start < len(runes) && runes[start-1] != ' ' {
		start++
	}
	end := min(start+excerptRunes, len(runes))
	out := string(runes[start:end])
	if !utf8.ValidString(out) {
		return ""
	}
	if start > 0 {
		out = "…" + out
	}
	if end < len(runes) {
		out += "…"
	}
	return out
}

func indexRunes(hay, needle []rune) int {
	if len(needle) == 0 {
		return -1
	}
outer:
	for i := 0; i+len(needle) <= len(hay); i++ {
		for j, r := range needle {
			if hay[i+j] != r {
				continue outer
			}
		}
		return i
	}
	return -1
}
