// Per-person DatabaseRoles: the console creates, as the
// signed-in user, a CloudNativePG DatabaseRole for one person on one
// Cluster, its password generated by CloudNativePG (spec.password mode
// generate, CloudNativePG 1.31) into a Secret CloudNativePG owns. The
// console never sees the password. The role is labelled personal and
// annotated with the person's pgAdmin username, which every PgAdmin
// registering the Cluster turns into a personal (non-shared) server of
// that user. Nothing here grants privileges the user could not grant by
// creating the DatabaseRole themselves: the API server authorizes the
// create under their name.

// PersonalRoleRequest is one per-person role.
type PersonalRoleRequest struct {
	Namespace, Cluster string
	// Role is the PostgreSQL role name.
	Role string
	// PgAdminUser is the pgAdmin username whose personal server it becomes.
	PgAdminUser string
	// InRoles are the roles it is a member of (CloudNativePG grants them).
	InRoles []string
	// CreatedBy is the Kubernetes username of the requester (an
	// annotation, for the audit trail next to the API server's own).
	CreatedBy string
}

// PersonalRole is what was created.
type PersonalRole struct {
	// Name is the DatabaseRole object; PasswordSecret the Secret
	// CloudNativePG generates the password into.
	Name, PasswordSecret string
}

// AnnotationCreatedBy names who asked the console for a personal role.
const AnnotationCreatedBy = pgtoolboxv1alpha1.ReservedKeyPrefix + "created-by"

// ErrPasswordGenerationUnavailable says the CloudNativePG of this cluster
// cannot generate a DatabaseRole's password (before 1.31).
var ErrPasswordGenerationUnavailable = errors.New("password generation unavailable")

// PersonalRoleName is the DatabaseRole object's name: the Cluster, then the
// role with underscores as dashes; "" when no valid name results.
func PersonalRoleName(cluster, role string) string {
	suffix := strings.Trim(strings.ReplaceAll(role, "_", "-"), "-")
	name := cluster + "-" + suffix
	if suffix == "" || len(name) > 253 {
		return ""
	}
	return name
}

// PersonalRoleObject is the DatabaseRole the console creates. It is
// unstructured because spec.password is newer than the vendored
// CloudNativePG API (1.30).
func PersonalRoleObject(req PersonalRoleRequest) *unstructured.Unstructured {
	name := PersonalRoleName(req.Cluster, req.Role)
	inRoles := make([]any, 0, len(req.InRoles))
	for _, role := range req.InRoles {
		inRoles = append(inRoles, role)
	}
	spec := map[string]any{
		"cluster":  map[string]any{"name": req.Cluster},
		"name":     req.Role,
		"ensure":   "present",
		"login":    true,
		"comment":  "personal role of " + req.PgAdminUser + " (console)",
		"password": map[string]any{"mode": "generate"},
	}
	if len(inRoles) > 0 {
		spec["inRoles"] = inRoles
	}
	u := &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": cnpgv1.SchemeGroupVersion.String(),
		"kind":       "DatabaseRole",
		"metadata": map[string]any{
			"name":      name,
			"namespace": req.Namespace,
			"labels":    map[string]any{pgtoolboxv1alpha1.LabelPersonalRole: pgtoolboxv1alpha1.PersonalRoleLabelValue},
			"annotations": map[string]any{
				pgtoolboxv1alpha1.AnnotationPgAdminUser: req.PgAdminUser,
				AnnotationCreatedBy:                     req.CreatedBy,
			},
		},
		"spec": spec,
	}}
	return u
}

// CreatePersonalDatabaseRole creates the role's DatabaseRole as the user.
// Strict field validation makes a CloudNativePG without password
// generation answer with an unknown spec.password, reported as
// ErrPasswordGenerationUnavailable rather than a role created without a
// password.
func (w *UserWriter) CreatePersonalDatabaseRole(ctx context.Context, req PersonalRoleRequest) (PersonalRole, error) {
	object := PersonalRoleObject(req)
	if object.GetName() == "" {
		return PersonalRole{}, &WriteError{Status: 422, Text: "creating the database role: no valid object name for this Cluster and role"}
	}
	ctx, cancel := context.WithTimeout(ctx, w.timeout)
	defer cancel()
	err := w.c.Create(ctx, object, client.FieldValidation("Strict"))
	switch {
	case err == nil:
		return PersonalRole{Name: object.GetName(), PasswordSecret: object.GetName() + "-password"}, nil
	case passwordFieldUnknown(err):
		return PersonalRole{}, &WriteError{
			Status: 501, cause: errors.Join(ErrPasswordGenerationUnavailable, err),
			Text: "creating the database role: not available on this CloudNativePG minor (generated DatabaseRole passwords need CloudNativePG 1.31 or later)",
		}
	case apierrors.IsAlreadyExists(err):
		return PersonalRole{}, &WriteError{Status: 409, Text: "creating the database role: DatabaseRole " + object.GetName() + " already exists", cause: err}
	}
	return PersonalRole{}, classify("creating the database role", err)
}

// passwordFieldUnknown reports an API error refusing spec.password as a
// field the DatabaseRole schema does not have.
func passwordFieldUnknown(err error) bool {
	var status apierrors.APIStatus
	if !errors.As(err, &status) {
		return false
	}
	message := err.Error()
	return strings.Contains(message, "spec.password") &&
		(strings.Contains(message, "unknown field") || strings.Contains(message, "not declared in schema"))
}
